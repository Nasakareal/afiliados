    </p>

    <h2>1. Responsable y contacto</h2>
    <p>
      GZ es responsable del tratamiento de la información descrita en esta política.
      Para consultas de privacidad, acceso, rectificación, cancelación, oposición o
      eliminación de datos, escribe a
      <a href="mailto:contacto@gladyadorez.com">contacto@gladyadorez.com</a>.
    </p>

    <h2>2. Información que tratamos</h2>
    <p>Según las funciones utilizadas y los permisos del usuario, el sistema puede tratar:</p>
    <ul>
      <li>
        <strong>Datos de la cuenta:</strong> nombre, correo electrónico, credenciales
        protegidas, roles, permisos y tokens de sesión.
      </li>
      <li>
        <strong>Datos de afiliados o personas registradas:</strong> nombre, apellidos,
        edad, sexo, teléfono, correo electrónico, domicilio, municipio, localidad,
        colonia, código postal, sección y distritos electorales, ubicación, perfil,
        observaciones, estatus y fecha de registro o convencimiento.
      </li>
      <li>
        <strong>Contenido operativo:</strong> actividades, lugares, comunicados,
        reportes y registros creados por usuarios autorizados.
      </li>
      <li>
        <strong>Registros de lonas:</strong> fotografía, dirección, coordenadas,
        sección, nombre de la persona responsable y usuario que realizó la captura.
      </li>
      <li>
        <strong>Datos del dispositivo:</strong> identificador para notificaciones
        push, plataforma del dispositivo y fecha de última actividad.
      </li>
      <li>
        <strong>Datos técnicos y de seguridad:</strong> dirección IP, fecha y hora de
        acceso, solicitudes al servidor, errores y registros necesarios para prevenir
        abusos y resolver fallas.
      </li>
    </ul>
    <p>
      Algunos registros pueden revelar afiliación, participación o preferencias de
      carácter político y, por tanto, pueden considerarse datos personales sensibles.
      Solamente deben ser capturados por personal autorizado y con la base legal o el
      consentimiento que corresponda.
    </p>

    <h2>3. Permisos del dispositivo</h2>
    <ul>
      <li>
        <strong>Cámara o archivos multimedia:</strong> se utilizan cuando el usuario
        decide tomar o seleccionar una fotografía para documentar una lona.
      </li>
      <li>
        <strong>Ubicación:</strong> se utiliza cuando el usuario registra o selecciona
        un punto en el mapa. La ubicación se asocia al registro correspondiente.
      </li>
      <li>
        <strong>Notificaciones:</strong> permiten recibir comunicados operativos. El
        sistema conserva el token técnico necesario para entregar estos mensajes.
      </li>
    </ul>
    <p>
      Estos permisos pueden administrarse desde la configuración del dispositivo. Al
      desactivarlos, algunas funciones relacionadas podrían dejar de estar disponibles.
    </p>

    <h2>4. Finalidades del tratamiento</h2>
    <ul>
      <li>Autenticar usuarios y aplicar controles de acceso y permisos.</li>
      <li>Administrar afiliados, actividades, comunicados, ubicaciones y evidencias fotográficas.</li>
      <li>Generar mapas, consultas, estadísticas y reportes internos.</li>
      <li>Enviar notificaciones relacionadas con la operación de la aplicación.</li>
      <li>Proteger la plataforma, prevenir accesos no autorizados y atender incidencias.</li>
      <li>Cumplir obligaciones legales y atender solicitudes de las autoridades competentes.</li>
    </ul>
    <p>No utilizamos los datos personales para publicidad personalizada ni los vendemos.</p>

    <h2>5. Compartición de información</h2>
    <p>
      La información puede ser tratada por proveedores indispensables de alojamiento,
      almacenamiento, seguridad, mapas y entrega de notificaciones, exclusivamente para
      prestar esos servicios y bajo las medidas aplicables de confidencialidad. También
      podrá comunicarse cuando exista una obligación legal, una orden válida de
      autoridad o sea necesario proteger derechos y seguridad.
    </p>
    <p>
      Algunos proveedores tecnológicos pueden procesar información en otros países y
      aplicar sus propias políticas de privacidad. No compartimos bases de datos con
      terceros para que comercialicen información personal.
    </p>

    <h2>6. Conservación y eliminación</h2>
    <p>
      Conservamos la información durante el tiempo necesario para las finalidades
      operativas descritas, mientras la cuenta o el registro permanezca activo y por
      los plazos adicionales exigidos por obligaciones legales, seguridad o resolución
      de controversias. Después, la información se elimina, anonimiza o bloquea de
      manera segura, según corresponda.
    </p>
    <p>
      El titular o usuario puede solicitar la eliminación de su cuenta o de sus datos
      mediante el correo indicado en esta política. La solicitud será verificada para
      proteger al titular y se atenderá conforme a la legislación aplicable. Cierta
      información podrá conservarse cuando exista una obligación legal o un motivo
      legítimo de seguridad.
    </p>

    <h2>7. Seguridad</h2>
    <p>
      Aplicamos controles razonables de acceso, autenticación, permisos y protección
      técnica y organizativa. Ningún sistema es completamente infalible, pero limitamos
      el acceso a personal autorizado y revisamos los incidentes que puedan afectar la
      confidencialidad, integridad o disponibilidad de la información.
    </p>

    <h2>8. Derechos y opciones</h2>
    <p>
      Las personas pueden solicitar acceso a sus datos, su rectificación cuando sean
      inexactos, su cancelación o eliminación, oponerse a determinados tratamientos,
      limitar su uso o revocar el consentimiento cuando sea aplicable. Para ejercer
      estos derechos, envía una solicitud a
      <a href="mailto:contacto@gladyadorez.com">contacto@gladyadorez.com</a> con la
      información necesaria para identificar el registro y acreditar la titularidad.
    </p>

    <h2>9. Privacidad de menores</h2>
    <p>
      La aplicación es una herramienta de trabajo para usuarios autorizados y no está
      dirigida a menores de edad. No se deben registrar deliberadamente datos de
      menores sin la autorización y base legal correspondientes. Si detectamos un
      registro indebido, tomaremos medidas para eliminarlo o restringirlo.
    </p>

    <h2>10. Cambios a esta política</h2>
    <p>
      Podemos actualizar esta política cuando cambien las funciones, los proveedores o
      las obligaciones legales. La versión vigente se publicará permanentemente en
      esta misma dirección e indicará la fecha de la última actualización.
    </p>

